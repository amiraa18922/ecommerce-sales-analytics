import pandas as pd

# 1. LOAD YOUR FILE
filename = 'ecommerce_sales_analytics_5000.csv'
df = pd.read_csv(filename)

print("File loaded successfully. Here are the first few rows:")
print(df.head())

# 2. CLEAN UP THE COLUMN NAMES (Makes them lowercase with underscores instead of spaces)
df.columns = df.columns.str.strip().str.lower().str.replace(' ', '_')

# 3. DROP EXACT DUPLICATE ROWS
df = df.drop_duplicates()

# 4. FIX MISSING VALUES (Fills empty spots so they don't break things later)
if 'quantity' in df.columns:
    df['quantity'] = df['quantity'].fillna(0)

if 'unit_price' in df.columns:
    df['unit_price'] = df['unit_price'].fillna(df['unit_price'].median())

# 5. EXPORT THE CLEANED FILE
cleaned_filename = 'cleaned_ecommerce_data.csv'
df.to_csv(cleaned_filename, index=False)

print(f"\nSUCCESS! Your cleaned file has been saved as '{cleaned_filename}'")